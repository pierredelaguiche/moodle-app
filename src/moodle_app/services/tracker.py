"""Progress per course and per week: how much of what Moodle published you have downloaded and marked as reviewed.

A week is a Moodle section (section 0 is "General", not a week). A file counts toward a week unless you ignored it:
`pending` and `downloaded` files are the denominator, files you ticked as reviewed are the numerator. The current week
comes from the course start date (section N is taken to be week N).
"""
from __future__ import annotations

import re
from pathlib import Path

WEEK = 7 * 86400
SOURCE_LINE = re.compile(r"(?m)^(?:source:\s*(.+)|# generated by .* from (.+))$")


def notes_by_source(ctx, module):
    """{source path inside the module: note path inside the study folder} for every generated note (read from its header)."""
    out_dir = Path(ctx.root) / module / ctx.settings.notes.get("output_dir", "Notes")
    found = {}
    if not out_dir.is_dir():
        return found
    for f in out_dir.rglob("*"):
        if not f.is_file() or f.suffix not in (".md", ".py") or f.name.startswith("."):
            continue
        try:
            head = f.read_text(encoding="utf-8", errors="replace")[:600]
        except OSError:
            continue
        m = SOURCE_LINE.search(head)
        if m:
            src = (m.group(1) or m.group(2)).strip()
            if f.suffix == ".md" or src not in found:           # a summary beats a code stub as "the note" of a source
                found[src] = f.relative_to(ctx.root).as_posix()
    return found


def term_week(startdate, enddate, now):
    """(current week number or None, 'before'|'running'|'over'|'unknown')."""
    if not startdate:
        return None, "unknown"
    if now < startdate:
        return 0, "before"
    if enddate and now > enddate + WEEK:
        return int((enddate - startdate) // WEEK) + 1, "over"
    return int((now - startdate) // WEEK) + 1, "running"


PAST_NO_END = 300 * 86400                    # a course without an end date counts as finished this long after it started


def finished(course, now):
    """True when the course's term is over: its end date (plus a week) has passed, or, with no end date, it started more
    than PAST_NO_END ago. Courses from Y1 and Y2 are followed for their files, not tracked."""
    start, end = course["startdate"] or 0, course["enddate"] or 0
    if end:
        return now > end + WEEK
    return bool(start) and now - start > PAST_NO_END


def build(ctx, now=None):
    now = now or ctx.ts()
    reviewed = ctx.reviewed.refs("file")
    out = []
    for c in ctx.courses.tracked():
        if finished(c, now):                     # earlier years: nothing to catch up on, so not on the Tracker (or "behind")
            continue
        names = {s["section_no"]: s["name"] for s in ctx.structure.sections(c["id"])}
        weeks = {}
        module = c["folder_rel"] or ""
        notes = notes_by_source(ctx, module) if module else {}
        for f in ctx.files.by_course(c["id"]):
            if f.status == "ignored":
                continue
            w = weeks.setdefault(f.section_no, {"no": f.section_no, "name": names.get(f.section_no) or f.sec_name or f"Week {f.section_no}",
                                                "files": []})
            w["files"].append({"key": f.key, "name": f.filename, "status": "new" if f.status == "pending" else (
                "update" if f.has_update else "downloaded"), "reviewed": f.key in reviewed and f.status == "downloaded",
                "rel": f.rel_path, "size": f.size, "moodle": f.moodle_name,
                "note": notes.get(f.rel_path[len(module) + 1:]) if module and f.rel_path.startswith(module + "/") else None})
        cur, phase = term_week(c["startdate"], c["enddate"], now)
        rows, behind = [], 0
        for no in sorted(weeks):
            w = weeks[no]
            fl = sorted(w["files"], key=lambda x: x["name"].lower())
            total = len(fl)
            have = sum(1 for x in fl if x["status"] != "new")
            done = sum(1 for x in fl if x["reviewed"])
            pct = round(100 * done / total) if total else 0
            if no == 0:
                state = "general"
            elif total and done == total:
                state = "done"
            elif cur is None or phase == "before":
                state = "open"
            elif phase == "over" or no < cur:
                state = "behind"
            elif no == cur:
                state = "current"
            else:
                state = "upcoming"
            if state == "behind":
                behind += 1
            rows.append({"no": no, "name": w["name"], "total": total, "downloaded": have, "reviewed": done, "pct": pct,
                         "state": state, "files": fl, "notes": sum(1 for x in fl if x["note"])})
        tot = sum(r["total"] for r in rows if r["no"] != 0) or 0
        rev = sum(r["reviewed"] for r in rows if r["no"] != 0)
        nxt = ctx.conn.execute("SELECT title, due_ts FROM deadlines WHERE course_id=? AND gone=0 AND hidden=0 AND done=0 "
                               "AND status='open' AND due_ts>=? ORDER BY due_ts LIMIT 1", (c["id"], now)).fetchone()
        out.append({"id": c["id"], "short": c["shortname"], "name": c["fullname"], "start": c["startdate"], "end": c["enddate"],
                    "current_week": cur, "phase": phase, "pct": round(100 * rev / tot) if tot else 0, "reviewed": rev, "total": tot,
                    "behind": behind, "notes": sum(r["notes"] for r in rows), "weeks": rows, "next_deadline": {"title": nxt["title"], "due_ts": nxt["due_ts"]} if nxt else None})
    return {"now": now, "courses": out}


def set_reviewed(ctx, keys, on, now=None):
    """Mark files as reviewed (or not). Only downloaded files can be reviewed; returns how many changed."""
    now = now or ctx.ts()
    n = 0
    with ctx.conn:
        for k in keys:
            rec = ctx.files.get(k)
            if rec is None or rec.status != "downloaded":
                continue
            if on:
                ctx.reviewed.mark("file", k, now)
            else:
                ctx.reviewed.unmark("file", k)
            n += 1
    return n


def week_keys(ctx, course_id, section_no):
    return [f.key for f in ctx.files.by_course(course_id) if f.section_no == section_no and f.status == "downloaded"]
